/** Build srcset strings for the <Picture> component. */
export function srcSets(def: AssetDef) {
  const m = getManifest(def.id);
  const base = `/images/${m.group}/${def.id}`;
  const widths = [...m.widths].sort((a, b) => a - b);
  return {
    avif: widths.map((w) => `${base}-${w}.avif ${w}w`).join(", "),
    webp: widths.map((w) => `${base}-${w}.webp ${w}w`).join(", "),
    fallback: `${base}-${widths[Math.min(1, widths.length - 1)]}.webp`,
    width: m.width,
    height: m.height,
    ratio: m.ratio,
    blur: m.blur,
  };
}

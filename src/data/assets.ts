/**
 * Central asset registry.
 *
 * Components reference images ONLY by id (e.g. assets.models.a12.side).
 * To replace an image: drop a new `<id>.src.png` in assets-src/<group>/ and
 * run `npm run images`, or point an entry at a different id. No component
 * edits needed. Drop a new `<id>.src.png` in assets-src and run `npm run images`.
 *
 * `anchors` are named points in the *trimmed* image, as fractions (0-1) of
 * width/height. Hero shadow, wheel blur discs and the blueprint overlay are
 * positioned from them, so a replacement bike only needs ~10 numbers updated.
 */
import manifestJson from "./image-manifest.json";

export type AssetStatus = "official" | "derived" | "placeholder" | "generic";

export interface Anchors {
  frontWheel: { x: number; y: number; r: number };
  rearWheel: { x: number; y: number; r: number };
  /** y of the tyre/ground contact line */
  groundY: number;
}

export interface AssetDef {
  /** Key in image-manifest.json (generated by scripts/images.mjs) */
  id: string;
  alt: string;
  status: AssetStatus;
  replaceBefore: "launch" | "never";
  source: string;
  anchors?: Anchors;
}

interface ManifestEntry {
  group: string;
  width: number;
  height: number;
  ratio: number;
  widths: number[];
  blur: string;
}
const manifest = manifestJson as Record<string, ManifestEntry>;

export function getManifest(id: string): ManifestEntry {
  const entry = manifest[id];
  if (!entry) throw new Error(`Asset "${id}" is not in image-manifest.json. Run \`npm run images\`.`);
  return entry;
}

const official = (id: string, alt: string, source: string): AssetDef => ({
  id,
  alt,
  status: "official",
  replaceBefore: "launch",
  source,
});

